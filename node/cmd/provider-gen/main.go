// provider-gen discovers source providers without a hand-maintained import list.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"path/filepath"
	"strconv"

	"github.com/teamva-ai/teamva/node/provider"
)

func generate(root string) ([]byte, error) {
	entries, err := os.ReadDir(root)
	if err != nil {
		return nil, err
	}
	var imports, definitions bytes.Buffer
	count := 0
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		path := filepath.Join(root, entry.Name(), "provider.json")
		payload, err := os.ReadFile(path)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return nil, err
		}
		var metadata provider.Metadata
		decoder := json.NewDecoder(bytes.NewReader(payload))
		decoder.DisallowUnknownFields()
		if err := decoder.Decode(&metadata); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if err := decoder.Decode(new(any)); err != io.EOF {
			return nil, fmt.Errorf("%s: expected exactly one manifest object", path)
		}
		if err := metadata.Validate(); err != nil {
			return nil, err
		}
		if metadata.ID != entry.Name() {
			return nil, fmt.Errorf("provider ID %q must match directory %q", metadata.ID, entry.Name())
		}
		if _, err := os.Stat(filepath.Join(root, entry.Name(), "provider.go")); err != nil {
			return nil, fmt.Errorf("provider %s requires provider.go: %w", metadata.ID, err)
		}
		canonical, err := json.Marshal(metadata)
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&imports, "p%d %q\n", count, "github.com/teamva-ai/teamva/node/provider/"+entry.Name())
		fmt.Fprintf(&definitions, "definitionFromJSON(%s, p%d.Definition),\n", strconv.Quote(string(canonical)), count)
		count++
	}
	if count == 0 {
		return nil, fmt.Errorf("no source providers found in %s", root)
	}
	source := "// Code generated by provider-gen; DO NOT EDIT.\npackage catalog\nimport (\n\"github.com/teamva-ai/teamva/node/provider\"\n" + imports.String() + ")\nvar definitions = []provider.Definition{\n" + definitions.String() + "}\n"
	return format.Source([]byte(source))
}

func main() {
	root := flag.String("root", "provider", "provider source directory")
	out := flag.String("out", "provider/catalog/providers_generated.go", "generated registry")
	check := flag.Bool("check", false, "fail if generated registry is stale")
	flag.Parse()
	payload, err := generate(*root)
	if err == nil {
		current, readErr := os.ReadFile(*out)
		if readErr == nil && bytes.Equal(current, payload) {
			return
		}
		if *check {
			err = fmt.Errorf("provider registry is stale; run pnpm generate:providers")
		} else {
			err = os.WriteFile(*out, payload, 0o644)
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
